/**
 * Isolated QA fixture for the inline feed reply harness.
 *
 * Reads DATABASE_URL only from the orchestrator's generated env. It never loads
 * dotenv and refuses any non-loopback host, so an inherited production URL is a
 * configuration error rather than a write target.
 *
 * Usage: DATABASE_URL=... node scripts/qa-feed-inline-seed.mjs
 */
import assert from "node:assert/strict";
import bcrypt from "bcryptjs";
import { PrismaClient } from "../src/generated/prisma/client.js";

const url = process.env.DATABASE_URL;
assert.ok(url, "DATABASE_URL is required (generated by qa-feed-inline.mjs)");
const parsed = new URL(url);
assert.ok(["postgresql:", "postgres:"].includes(parsed.protocol));
assert.ok(
  ["127.0.0.1", "localhost", "::1"].includes(parsed.hostname),
  "QA seed refuses a non-loopback database host",
);

const prisma = new PrismaClient({ datasources: { db: { url } } });

export const QA = {
  password: "QaPass123",
  viewerEmail: "qa-viewer@example.invalid",
  viewerUsername: "qa_viewer",
  users: {
    viewer: "qa-feed-user-viewer",
    author: "qa-feed-user-author",
    other: "qa-feed-user-other",
    bot: "qa-feed-user-bot",
    admin: "qa-feed-user-admin",
  },
  board: "qa-feed-board",
  articles: {
    main: "qa-feed-main",
    ai: "qa-feed-ai-only",
    empty: "qa-feed-empty",
    countOnly: "qa-feed-count-only",
    long: "qa-feed-long",
    otherPending: "qa-feed-other-pending",
    bulkPrefix: "qa-feed-bulk-",
  },
  comments: {
    mainFirst: "qa-feed-comment-main-1",
    mainSecond: "qa-feed-comment-main-2",
    mainNested: "qa-feed-comment-main-nested",
    mainOwnPending: "qa-feed-comment-main-own-pending",
  },
};

async function seed() {
  await prisma.article.deleteMany({ where: { id: { startsWith: "qa-feed-" } } });
  await prisma.user.deleteMany({ where: { id: { startsWith: "qa-feed-user-" } } });
  await prisma.board.deleteMany({ where: { id: QA.board } });
  await prisma.sensitiveKeyword.deleteMany({ where: { keyword: "[qa:reject]" } });

  // AI safety classifications produce pending_review. A definite rejection must
  // exercise the real local-keyword branch instead of mislabeling an AI review.
  await prisma.sensitiveKeyword.create({
    data: { keyword: "[qa:reject]", category: "general", isActive: true },
  });

  await prisma.board.create({
    data: { id: QA.board, name: "QA 茶桌", slug: "qa-feed", sortOrder: 0 },
  });

  const passwordHash = await bcrypt.hash(QA.password, 10);
  const rows = [
    [QA.users.viewer, QA.viewerUsername, QA.viewerEmail, false, "user"],
    [QA.users.author, "qa_author", "qa-author@example.invalid", false, "user"],
    [QA.users.other, "qa_other", "qa-other@example.invalid", false, "user"],
    [QA.users.bot, "qa_bot", "qa-bot@example.invalid", true, "system"],
    [QA.users.admin, "qa_admin", "qa-admin@example.invalid", false, "admin"],
  ];
  await prisma.user.createMany({
    data: rows.map(([id, username, email, isSynthetic, role], n) => ({
      id,
      uid: 880000 + n,
      username,
      email,
      passwordHash,
      preferenceTags: [],
      role,
      isSynthetic,
      level: 1,
    })),
  });

  const now = Date.now();
  const hour = 3600_000;
  const article = (id, offsetHours, overrides = {}) => ({
    id,
    type: "discussion",
    title: `QA ${id}`,
    content: `QA fixture body for ${id}`,
    tags: [],
    images: [],
    boardId: QA.board,
    status: "published",
    visibility: "public",
    origin: "human",
    authorId: QA.users.author,
    createdAt: new Date(now - offsetHours * hour),
    updatedAt: new Date(now - offsetHours * hour),
    ...overrides,
  });

  const bulk = Array.from({ length: 40 }, (_, n) =>
    article(`${QA.articles.bulkPrefix}${String(n).padStart(2, "0")}`, 20 + n));
  await prisma.article.createMany({
    data: [
      article(QA.articles.main, 1, { title: "QA 主帖：默认展开与内联回复" }),
      article(QA.articles.ai, 2, { title: "QA 纯 AI 回复帖" }),
      article(QA.articles.empty, 3, { title: "QA 零回复帖" }),
      article(QA.articles.countOnly, 4, { title: "QA 计数仍可见但无顶层预览帖" }),
      article(QA.articles.long, 5, { title: "QA 超长评论帖" }),
      article(QA.articles.otherPending, 6, { title: "QA 他人待审帖" }),
      ...bulk,
    ],
  });

  const comment = (id, articleId, authorId, content, overrides = {}) => ({
    id,
    articleId,
    authorId,
    content,
    images: [],
    status: "published",
    origin: "human",
    ...overrides,
  });
  await prisma.comment.createMany({
    data: [
      comment(QA.comments.mainFirst, QA.articles.main, QA.users.other,
        "第一条真人回复：预览默认应该展开。"),
      comment(QA.comments.mainSecond, QA.articles.main, QA.users.author,
        "第二条真人回复：它旁边的回复按钮指向真实父评论。"),
      comment("qa-feed-comment-main-ai", QA.articles.main, QA.users.bot,
        "有真人回复时，AI 不应该被拿来凑数。", { origin: "ai_autonomous" }),
      comment(QA.comments.mainNested, QA.articles.main, QA.users.other,
        "这条是嵌套回复，只进整树计数，不进顶层预览。",
        { parentId: QA.comments.mainFirst }),
      comment(QA.comments.mainOwnPending, QA.articles.main, QA.users.viewer,
        "本人待审评论应该只对本人可见。", { status: "pending_review" }),

      comment("qa-feed-comment-ai-only", QA.articles.ai, QA.users.bot,
        "零可见真人顶层回复时，才允许预览一条带标注的 AI 回复。",
        { origin: "ai_autonomous" }),

      comment("qa-feed-comment-hidden-parent", QA.articles.countOnly, QA.users.bot,
        "未标注的合成评论对读者隐藏。", { origin: null }),
      comment("qa-feed-comment-visible-orphan", QA.articles.countOnly, QA.users.other,
        "父评论不可见时，这条可见子评论仍计入整树，但不是顶层预览。",
        { parentId: "qa-feed-comment-hidden-parent" }),

      comment("qa-feed-comment-long", QA.articles.long, QA.users.other,
        `🍵${"茶".repeat(1200)}尾部`),
      comment("qa-feed-comment-long-url", QA.articles.long, QA.users.author,
        `长链接也必须折断：https://example.invalid/${"a".repeat(900)}`),

      comment("qa-feed-comment-other-pending", QA.articles.otherPending, QA.users.other,
        "他人的待审评论对当前登录者不可见。", { status: "pending_review" }),

      ...bulk.flatMap((_, n) => [
        comment(`qa-feed-comment-bulk-${n}-1`, `${QA.articles.bulkPrefix}${String(n).padStart(2, "0")}`,
          QA.users.other, `bulk ${n} first human reply`),
        comment(`qa-feed-comment-bulk-${n}-2`, `${QA.articles.bulkPrefix}${String(n).padStart(2, "0")}`,
          QA.users.author, `bulk ${n} second human reply`),
      ]),
    ],
  });

  console.log(JSON.stringify({
    ok: true,
    viewer: { email: QA.viewerEmail, username: QA.viewerUsername, password: QA.password },
    articles: QA.articles,
    comments: QA.comments,
  }));
}

seed()
  .catch((error) => {
    console.error("QA seed failed:", error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
