# ─── 工具函数 ──────────────────────────────────

def gen_id():
    return str(uuid.uuid4())

def hash_password(pw: str) -> str:
    return bcrypt.hashpw(pw.encode(), bcrypt.gensalt()).decode()

def random_choice_weighted(items, weights=None, k=1):
    """从列表中按权重随机选择"""
    if weights is None:
        return random.choices(items, k=k)[0] if k == 1 else random.choices(items, k=k)
    return random.choices(items, weights=weights, k=k)[0] if k == 1 else random.choices(items, weights=weights, k=k)

